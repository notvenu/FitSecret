// Turns supabase/live-schema.sql (the output of scripts/export-schema.sql) into an idempotent migration that brings a database
// built from 0001–0005 up to what the live project runs (migrations 0006–0015 were applied live but never committed).
//   node scripts/live-to-migration.mjs > supabase/migrations/0006_live_baseline.sql
// Safe on the live database too: every statement is "if not exists" / "create or replace" / drop-then-create for policies & triggers.
// ponytail: column defaults, check constraints and extra indexes are not in the export; add them here if a later export includes them.
import { readFileSync } from 'node:fs';

const src = readFileSync(new URL('../supabase/live-schema.sql', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const out = [`-- GENERATED by scripts/live-to-migration.mjs from supabase/live-schema.sql. Do not edit by hand.
-- Stands in for migrations 0006–0015, which were applied to the live project but never committed.
-- Already applied live: running it there changes nothing. Fresh databases: run after 0001–0005.
`];

// 1. Tables and columns. New tables get the shared sync columns; every live column is added if missing.
const tables = [...src.matchAll(/^-- table (\w+): rls (ON|OFF)[^\n]*\n--\s+([^\n]+)/gm)].map(([, name, rls, cols]) => ({
  name, rls: rls === 'ON',
  cols: cols.split(/, (?=[a-z_]+ )/).map((c) => { const i = c.indexOf(' '); return [c.slice(0, i), c.slice(i + 1)]; }),
}));
out.push('-- ---------- Tables ----------');
for (const t of tables) {
  const hasId = t.cols.some(([c]) => c === 'id');
  if (hasId) out.push(`create table if not exists ${t.name} (id uuid primary key default gen_random_uuid(), created_at timestamptz, updated_at timestamptz, deleted boolean default false, seq bigint);`);
  for (const [c, type] of t.cols) if (!(hasId && ['id', 'created_at', 'updated_at', 'deleted', 'seq'].includes(c))) out.push(`alter table ${t.name} add column if not exists ${c} ${type};`);
  if (t.cols.some(([c]) => c === 'seq')) out.push(`create index if not exists ${t.name}_seq_idx on ${t.name} (seq);`);
  if (t.rls) out.push(`alter table ${t.name} enable row level security;`);
}

// 2. Functions, verbatim (create or replace).
out.push('\n-- ---------- Functions ----------');
for (const [f] of src.matchAll(/CREATE OR REPLACE FUNCTION[\s\S]*?\$function\$\n;/g)) out.push(f + '\n');

// 3. Views, verbatim.
out.push('-- ---------- Views ----------');
for (const [v] of src.matchAll(/^create or replace view [\s\S]*?;$/gm)) out.push(v + '\n');

// 4. Row level security policies.
out.push('-- ---------- Policies ----------');
for (const [p, name, table] of src.matchAll(/^create policy (\w+) on (\w+) [^\n]*(?:\n(?!\n)[^\n]*)*;$/gm)) out.push(`drop policy if exists ${name} on ${table};\n${p}`);

// 5. Triggers.
out.push('\n-- ---------- Triggers ----------');
for (const [tr, name, table] of src.matchAll(/^CREATE TRIGGER (\w+) [^\n]*? ON public\.(\w+) [^\n]*;$/gm)) out.push(`drop trigger if exists ${name} on ${table};\n${tr}`);

// 6. Who may call each function: grant the listed API roles, revoke the rest (Postgres grants execute to PUBLIC by default).
out.push('\n-- ---------- Function grants ----------');
for (const [, fn, roles] of src.matchAll(/^-- grant execute on (\w+) to ([^\n]+)$/gm)) {
  const has = roles.split(', ');
  const api = ['anon', 'authenticated', 'service_role'];
  const revoke = ['public', ...api.filter((r) => !has.includes(r) && !has.includes('PUBLIC'))].filter((r) => r !== 'public' || !has.includes('PUBLIC'));
  if (revoke.length) out.push(`revoke execute on function ${fn} from ${revoke.join(', ')};`);
  const grant = api.filter((r) => has.includes(r) || has.includes('PUBLIC'));
  if (grant.length) out.push(`grant execute on function ${fn} to ${grant.join(', ')};`);
}

console.log(out.join('\n'));
